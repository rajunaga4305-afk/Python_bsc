# Append method example

fruits = ["Apple", "Banana", "Orange"]

fruits.append("Mango")

print(fruits)

# Extend method example

fruits = ["Apple", "Banana"]
more_fruits = ["Mango", "Orange"]

fruits.extend(more_fruits)

print(fruits)

# Insert method example

fruits = ["Apple", "Banana", "Orange"]

fruits.insert(1, "Mango")

print(fruits)